#!/usr/bin/env python3
"""Independently calculate the seven PCG policy fixture replacements; never run C#.

Uses only the declared FNV/PCG algorithm and the existing specification-derived
F01 mapping validator. Historical MT fixture bytes are never modified.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import conformance_random as laws

MASK = (1 << 64) - 1
POLICY = "docs/random-policy-pcg32.md"


def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & MASK
    return value


def words(seed, stream):
    increment = (stream << 1) | 1
    state = increment & MASK
    state = (((state + seed) & MASK) * 6364136223846793005 + increment) & MASK
    while True:
        prior = state
        state = (prior * 6364136223846793005 + increment) & MASK
        shifted = (((prior >> 18) ^ prior) >> 27) & 0xffffffff
        rotation = prior >> 59
        yield ((shifted >> rotation) | (shifted << ((-rotation) & 31))) & 0xffffffff


def context(seed, domain, name):
    identity = (domain + "\0" + name).encode("ascii")
    return words(fnv(b"oc2-pcg32/state\0" + identity) ^ seed,
                 fnv(b"oc2-pcg32/stream\0" + identity) & ((1 << 63) - 1))


def verify_vectors():
    engine = words(42, 54)
    assert [next(engine) for _ in range(6)] == [0xa15c02b7, 0x7b47f409, 0xba1d3330, 0x83d2f293, 0xbfa4784b, 0xcbed606e]
    engine = context(0, "gameplay", "session/main")
    assert [next(engine) for _ in range(6)] == [0x1f35ca66, 0x7064c4ec, 0x652d0716, 0x5dd5c3d6, 0xb9e0258e, 0x5dd19c44]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def replacement(original, policy_hash):
    case = copy.deepcopy(original)
    case["id"] += ".pcg32-v1"
    case["revision"] = 2
    case["randomness"]["policy"] = {"id": "oc2-pcg32", "version": "1", "sha256": policy_hash}
    case.setdefault("extensions", {})["policyVariant"] = {"replaces": original["id"], "policy": "oc2-pcg32/1"}
    sources = case["evidence"]["sources"]
    for source in sources:
        if source["file"].endswith("random-policy.md"):
            source.update(file="../../random-policy-pcg32.md", section="portable-fixture-replay-contexts", sha256=policy_hash)
    case["evidence"]["limitations"] = [
        "PCG32 policy variant of " + original["id"] + "; the reference fixture is independently recorded.",
        "Expected code independently calculated from the declared FNV/PCG32 formulas after checking published and derived-context vectors; not generated by the managed adapter.",
        "Authored sampler boundary and implementation-policy regression only; no gameplay parent or original-program observation."
    ]
    operation = case["boundary"]["operation"]
    args = case["boundary"]["arguments"]
    if laws.nonconstant(operation, args):
        domain = args["domain"]["value"]
        seed, draws = laws.context_values(case["randomness"]["contexts"], domain)
        assert draws <= 1_000_000
        engine = context(seed, domain, "fixture")
        for _ in range(draws):
            next(engine)
        raw = next(engine)
        law, schema = laws.SAMPLERS[operation]
        code = {"$type": "i32" if law.startswith("primary-") else "u32", "value": str(raw >> 17 if law.startswith("primary-") else raw)}
        result = laws.mapped(law, {key: args[key] for key in schema}, code)
        case["expected"]["result"] = result
        for event in case["expected"]["trace"]:
            if event["kind"] == "random":
                event["payload"].update(code=code, result=result)
            elif event["kind"] == "return":
                event["payload"]["result"] = result
    return case


def generated():
    verify_vectors()
    policy_hash = digest((ROOT / POLICY).read_bytes())
    outputs, selected = {}, []
    for path in sorted((ROOT / "docs/algorithms/conformance").glob("*.json")):
        original_bytes = path.read_bytes()
        original = json.loads(original_bytes)
        target, data, case = path, original_bytes, original
        if original["randomness"]["mode"] == "implementation-replay":
            case = replacement(original, policy_hash)
            target = ROOT / "docs/algorithms/conformance-pcg32" / path.name
            data = (json.dumps(case, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
            outputs[target] = data
        selected.append({"historicalId": original["id"], "historicalPath": path.relative_to(ROOT).as_posix(), "historicalSha256": digest(original_bytes),
                         "id": case["id"], "path": target.relative_to(ROOT).as_posix(), "sha256": digest(data), "operation": case["boundary"]["operation"]})
    assert len(selected) == 57 and len(outputs) == 7 and len({c["operation"] for c in selected}) == 15
    manifest = {"format": "openciv2-managed-conformance-selection/1", "policy": {"id": "oc2-pcg32", "version": "1", "file": POLICY, "sha256": policy_hash}, "cases": selected}
    outputs[ROOT / "docs/conformance/selection.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write reviewed versioned replacements; default verifies")
    args = parser.parse_args()
    for path, data in generated().items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.is_file() or path.read_bytes() != data:
            raise SystemExit("Stale PCG fixture/selection: " + str(path.relative_to(ROOT)))
    print("Verified seven PCG32 replacements and all 57 selected fixture identities.")


if __name__ == "__main__":
    main()
