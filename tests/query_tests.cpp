StoredSave sample() {
    // Authored logical F02/F06 input. Codec byte expectations are independently
    // tested in save_tests.cpp; these tests concern projection and diagnosis.
    StoredSave save;
    save.map.header = {4, 2, 4, 0, 24, 1, 1};
    save.map.tiles.resize(4);
    for (auto& layer : save.map.remembered)
        layer.resize(4);
    for (auto& grid : save.map.coarse)
        grid.resize(1);
    save.map.regions[0].neighboring_water = std::numeric_limits<std::uint64_t>::max();
    save.globals.unit_end = 3;
    save.globals.city_end = 2;
    save.globals.view_civ = -1; // Observed stored value; sentinel semantics unresolved.
    save.units.resize(3);
    save.cities.resize(2);
    save.units[0].token = state::UnitToken{0x80000001};
    save.units[1].damage = 255; // Hole payload is neither removed nor validated as live.
    save.units[1].owner = state::CivilizationSlot{255};
    save.units[2].token = state::UnitToken{0xffffffff};
    save.cities[0].token = state::CityToken{17};
    save.cities[0].name.bytes[0] = 0xff;
    save.cities[0].name.bytes[2] = 0xfe; // Beyond NUL, still retained.
    save.cities[0].size = -128;
    save.cities[0].food_box = -32768;
    save.civilizations[0].gold = std::numeric_limits<std::int32_t>::min();
    save.civilizations[0].military_count = -123; // Retained, not an inferred live count.
    save.leaders.resize(1);
    return save;
}
StoredSnapshot inspect(const StoredSave& save) {
    return inspect_stored(encode_stored_save(save), FileKind::save, FileAccess::offline_omniscient);
}
const Record& record(const StoredSnapshot& snapshot, Section section, std::size_t slot) {
    const auto found =
        std::find_if(snapshot.records().begin(), snapshot.records().end(),
                     [&](const auto& r) { return r.key == RecordKey{section, slot}; });
    if (found == snapshot.records().end())
        throw std::runtime_error("Missing test record");
    return *found;
}
const Field& field(const Record& record, std::string_view name) {
    const auto found = std::find_if(record.fields.begin(), record.fields.end(),
                                    [&](const auto& f) { return f.name == name; });
    if (found == record.fields.end())
        throw std::runtime_error("Missing test field");
    return *found;
}
bool diagnostic(const StoredSnapshot& snapshot, std::string_view code) {
    return std::any_of(snapshot.diagnostics().begin(), snapshot.diagnostics().end(),
                       [&](const auto& d) { return d.code == code; });
}
